    print("   - https://www.alchemy.com/faucets/ethereum-sepolia")
    print("   - https://sepolia-faucet.pk910.de/")
    
    print("\n2. zkSync Era Sepolia:")
    print("   - https://faucets.chain.link/zksync-sepolia")
    print("   - https://www.alchemy.com/faucets/zksync-sepolia")
    
